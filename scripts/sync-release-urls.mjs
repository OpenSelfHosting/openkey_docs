#!/usr/bin/env node
/**
 * Sync desktop/mobile artifact URLs from the latest GitHub Release on openkey_app.
 * Run before build (or via `npm run sync:releases`). Committed output keeps CI working
 * when the repo is private; refresh after each release publish.
 */

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const OUT = join(ROOT, '.vitepress/theme/downloads/releaseUrls.generated.ts')

/** @type {readonly string} */
export const DEFAULT_REPO = 'OpenSelfHosting/openkey_app'

const REPO = process.env.OPENKEY_RELEASE_REPO || DEFAULT_REPO
const API = `https://api.github.com/repos/${REPO}/releases/latest`

/** Variant id → asset filename matchers (first match wins per variant). */
const VARIANT_RULES = [
  {
    id: 'windows-x64',
    match: (name) =>
      /windows-x64-setup\.exe$/i.test(name) ||
      (/windows/i.test(name) && /x64/i.test(name) && /\.(exe|zip|msix)$/i.test(name)),
  },
  {
    id: 'windows-arm64',
    match: (name) =>
      /windows-arm64/i.test(name) && /\.(exe|zip|msix)$/i.test(name),
  },
  {
    id: 'macos-arm64',
    match: (name) => /macos-arm64.*\.dmg$/i.test(name),
  },
  {
    id: 'macos-x64',
    match: (name) => /macos-x64.*\.dmg$/i.test(name),
  },
  {
    id: 'macos-universal',
    match: (name) => /macos-universal.*\.dmg$/i.test(name),
  },
  {
    id: 'linux-deb-x64',
    match: (name) => /linux-x64\.deb$/i.test(name),
  },
  {
    id: 'linux-deb-arm64',
    match: (name) => /linux-arm64\.deb$/i.test(name),
  },
  {
    id: 'linux-tar-x64',
    match: (name) => /linux-x64\.tar\.gz$/i.test(name),
  },
  {
    id: 'linux-tar-arm64',
    match: (name) => /linux-arm64\.tar\.gz$/i.test(name),
  },
  {
    id: 'android-apk',
    match: (name) => /android.*\.apk$/i.test(name) && !/\.apk\./i.test(name),
  },
]

function isSkippableAsset(name) {
  return (
    /\.(asc|sha256|sha512|sig|checksums?|blockmap)$/i.test(name) ||
    /\.SHA256/i.test(name) ||
    /checksum/i.test(name)
  )
}

/**
 * @param {Array<{ name: string; browser_download_url: string }>} assets
 * @returns {Record<string, string>}
 */
function mapAssets(assets) {
  /** @type {Record<string, string>} */
  const urls = {}
  const usable = assets.filter((a) => a.name && !isSkippableAsset(a.name))

  for (const rule of VARIANT_RULES) {
    const hit = usable.find((a) => rule.match(a.name))
    if (hit) urls[rule.id] = hit.browser_download_url
  }

  return urls
}

/**
 * @returns {Promise<{ tag: string | null; urls: Record<string, string>; publishedAt: string | null }>}
 */
async function fetchLatestRelease() {
  const headers = {
    Accept: 'application/vnd.github+json',
    'User-Agent': 'openkey-docs-sync-releases',
    'X-GitHub-Api-Version': '2022-11-28',
  }
  const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN
  if (token) headers.Authorization = `Bearer ${token}`

  const res = await fetch(API, { headers })
  if (res.status === 404) {
    return { tag: null, urls: {}, publishedAt: null }
  }
  if (!res.ok) {
    throw new Error(`GitHub API ${res.status}: ${await res.text()}`)
  }

  const data = await res.json()
  const assets = Array.isArray(data.assets) ? data.assets : []
  return {
    tag: data.tag_name ?? null,
    publishedAt: data.published_at ?? null,
    urls: mapAssets(assets),
  }
}

function emitTs({ tag, urls, publishedAt }) {
  const body = `// Generated by scripts/sync-release-urls.mjs — do not edit by hand.
// Re-run: npm run sync:releases

export const RELEASE_SOURCE_REPO = ${JSON.stringify(REPO)} as const

export const RELEASE_SYNC = {
  tag: ${tag ? JSON.stringify(tag) : 'null'},
  publishedAt: ${publishedAt ? JSON.stringify(publishedAt) : 'null'},
  syncedAt: ${JSON.stringify(new Date().toISOString())},
} as const

/** Variant id → browser_download_url from the latest GitHub Release. */
export const RELEASE_ARTIFACT_URLS: Record<string, string> = ${JSON.stringify(urls, null, 2)}
`
  writeFileSync(OUT, body, 'utf8')
}

async function main() {
  try {
    const release = await fetchLatestRelease()
    emitTs(release)
    const count = Object.keys(release.urls).length
    if (release.tag) {
      console.log(
        `sync-release-urls: ${REPO}@${release.tag} → ${count} artifact URL(s) → ${OUT}`,
      )
    } else {
      console.log(
        `sync-release-urls: no latest release on ${REPO} (or not accessible) — wrote empty map`,
      )
    }
  } catch (err) {
    console.error('sync-release-urls failed:', err instanceof Error ? err.message : err)
    process.exit(1)
  }
}

main()
